/**
 * Returns a randomized affirmation, optionally excluding a specific ID to avoid repeats
 */
export function getRandomAffirmation(excludeId?: string): DailyAffirmation {
  const pool = excludeId
    ? MINDFUL_AFFIRMATIONS.filter((item) => item.id !== excludeId)
    : MINDFUL_AFFIRMATIONS;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex] || MINDFUL_AFFIRMATIONS[0];
}

/**
 * Returns a deterministic daily affirmation based on current date,
 * guaranteeing a stable daily quote that changes every calendar day.
 */
export function getDailyAffirmation(): DailyAffirmation {
  const now = new Date();
  // Generate date seed: YYYYMMDD
  const dateKey = now.getFullYear() * 10000 + (now.getMonth() + 1) * 100 + now.getDate();
  const index = dateKey % MINDFUL_AFFIRMATIONS.length;
  return MINDFUL_AFFIRMATIONS[index];
}
